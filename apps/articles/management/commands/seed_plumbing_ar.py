class Command(BaseCommand):
    help = "Seed 5 Arabic plumbing articles."

    def handle(self, *args, **options):
        try:
            category = ServiceCategory.objects.get(slug=CATEGORY_SLUG)
        except ServiceCategory.DoesNotExist:
            self.stderr.write(f"Category '{CATEGORY_SLUG}' not found.")
            return

        author = staff_user()
        now = timezone.now()
        created = 0

        for data in ARTICLES:
            if Article.objects.filter(language="ar", slug=data["slug"]).exists():
                self.stdout.write(f"  skip  {data['slug']}")
                continue

            article = Article(
                translation_group=uuid.uuid4(),
                category=category,
                author=author,
                language="ar",
                status=Article.PUBLISHED,
                published_at=now,
                title=data["title"],
                slug=data["slug"],
                body=data["body"],
                meta_title=data["meta_title"],
                meta_description=data["meta_description"],
            )
            article.save()
            created += 1
            self.stdout.write(self.style.SUCCESS(f"  created  {article.title}"))

        self.stdout.write(self.style.SUCCESS(f"\nDone — {created} article(s) created."))
